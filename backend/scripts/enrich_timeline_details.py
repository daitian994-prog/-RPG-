def enrich_timeline(repository: LoreRepository) -> int:
    updated = 0
    for record_id, detail in DETAILS.items():
        record = repository.get("timeline", record_id)
        if not record:
            continue
        data = {**record["data"], **detail, "detail_version": "2.0", "detail_origin": "Riot 中英文官方地区页、人物传记与故事交叉整理"}
        repository.update("timeline", record_id, record["title"], data)
        updated += 1
    return updated


